export function LazyPageWrapper({ children, fallback, title }: LazyPageWrapperProps) {
  const defaultFallback = fallback || <DefaultPageSkeleton title={title} />;

  return (
    <Suspense fallback={defaultFallback}>
      {children}
    </Suspense>
  );
}

export default LazyPageWrapper;
